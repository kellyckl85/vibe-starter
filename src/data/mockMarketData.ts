// Helper to generate realistic candles
function generateCandles(basePrice: number, count: number = 30, volatility: number = 0.015) {
  const candles = [];
  let currentClose = basePrice * (1 - volatility * (count / 4));
  const now = new Date();

  for (let i = count; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toISOString().slice(5, 10);
    const delta = (Math.random() - 0.48) * volatility * currentClose;
    const open = currentClose;
    const close = Math.max(0.1, open + delta);
    const high = Math.max(open, close) + Math.random() * volatility * currentClose * 0.7;
    const low = Math.min(open, close) - Math.random() * volatility * currentClose * 0.7;
    const volume = Math.floor(Math.random() * 5000000 + 1000000);

    candles.push({
      time: dateStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    currentClose = close;
  }
  return candles;
}

